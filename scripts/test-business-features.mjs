import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import ts from 'typescript';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
const source=await readFile(new URL('../app/business-features.tsx',import.meta.url),'utf8');
await mkdir(new URL('../work/',import.meta.url),{recursive:true});
const output=new URL('../work/.business-features-test.mjs',import.meta.url);
await writeFile(output,ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022,jsx:ts.JsxEmit.ReactJSX}}).outputText);
const {currentPromotion,safePublicUrl,BusinessFacts,MerchantTestimonials,uruguayDay}=await import(output.href);
assert.equal(currentPromotion({promocion_titulo:'Oferta',promocion_inicio:'2026-10-21',promocion_fin:'2026-10-21'},'2026-10-21'),true);
assert.equal(currentPromotion({promocion_titulo:'Oferta',promocion_inicio:'2026-10-20',promocion_fin:'2026-10-21'},'2026-10-22'),false);
assert.equal(currentPromotion({promocion_titulo:'Oferta',promocion_inicio:'2026-02-30',promocion_fin:'2026-99-99'},'2026-10-21'),false);
assert.equal(currentPromotion({promocion_titulo:'Sin fecha'},'2026-10-21'),false);
assert.equal(safePublicUrl('javascript:alert(1)'),'');
assert.equal(safePublicUrl('https://example.com/menu'),'https://example.com/menu');
assert.equal(renderToStaticMarkup(React.createElement(BusinessFacts,{business:{}})),'');
const escaped=renderToStaticMarkup(React.createElement(BusinessFacts,{business:{historia_negocio:'<script>alert(1)</script>',persona_nombre:'Ana',menu_url:'javascript:alert(1)'}}));
assert.doesNotMatch(escaped,/<script>/);assert.doesNotMatch(escaped,/href=/);assert.match(escaped,/&lt;script&gt;/);
assert.equal(renderToStaticMarkup(React.createElement(MerchantTestimonials,{testimonials:[{id:'1',nombre_publico:'Ana',negocio_id:'missing',texto:'Experiencia'}],businesses:[]})),'');
assert.equal(uruguayDay(new Date('2026-10-22T01:00:00Z')),'2026-10-21');
console.log('Verificados: vencimiento local de promociones, fechas inválidas, enlaces seguros, escape de textos y ausencia de testimonios sin negocio publicado.');
